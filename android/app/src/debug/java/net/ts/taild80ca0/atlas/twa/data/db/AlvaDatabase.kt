package net.ts.taild80ca0.atlas.twa.data.db

import android.content.Context
import androidx.room.Database
import androidx.room.Room
import androidx.room.RoomDatabase
import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase

@Database(
    entities = [
        SyncStateEntity::class,
        CategoryEntity::class,
        CatalogItemEntity::class,
        CatalogStateEntity::class,
        ConfirmedItemEntity::class,
        ListItemEntity::class,
        CommandEntity::class,
        CommandSubjectEntity::class,
        SyncAliasEntity::class,
        CommandReceiptEntity::class,
        ArchivedItemEntity::class,
        ShoppingTripEntity::class,
        HabitualItemEntity::class,
        TombstoneEntity::class,
    ],
    version = AlvaMigrations.CURRENT_VERSION,
    exportSchema = true,
)
abstract class AlvaDatabase : RoomDatabase() {
    abstract fun syncState(): SyncStateDao
    abstract fun categories(): CategoryDao
    abstract fun catalog(): CatalogDao
    abstract fun confirmedItems(): ConfirmedItemDao
    abstract fun listItems(): ListItemDao
    abstract fun commands(): CommandDao
    abstract fun aliases(): AliasDao
    abstract fun receipts(): ReceiptDao
    abstract fun history(): HistoryDao
}

/**
 * Migration policy (also in docs/plans/android-local-persistence.md):
 *
 * - The local database holds actions that never reached the server, so a
 *   migration may never drop or recreate data. `fallbackToDestructiveMigration`
 *   is forbidden and absent from [AlvaDatabaseFactory]; a missing migration makes
 *   opening fail loudly instead of wiping the queue.
 * - Every version bump needs, in the same change: the new `schemas/<version>.json`
 *   (generated by Room), a [Migration] appended to [ALL] without gaps, and a
 *   migration test with data in the old tables. `AlvaMigrationsTest` (JVM) and
 *   `AlvaDatabaseMigrationTest` (instrumented) enforce this.
 * - Prefer additive steps (new nullable column, new table). Renames and type
 *   changes copy data into the new shape inside the migration.
 */
object AlvaMigrations {
    const val CURRENT_VERSION = 5

    /**
     * 1 -> 2 (issue #42, local matching): additive only. The synced dictionary gets
     * its table and revision row, and each command subject can remember the category
     * the device applied. Nothing existing is rewritten, so the list, the queue and
     * their UUIDs are exactly as they were; old subjects simply have no category.
     */
    val MIGRATION_1_2: Migration = object : Migration(1, 2) {
        override fun migrate(db: SupportSQLiteDatabase) {
            db.execSQL(
                "CREATE TABLE IF NOT EXISTS `catalog_items` (`public_id` TEXT NOT NULL, `name` TEXT NOT NULL, " +
                    "`normalized_name` TEXT NOT NULL, `category_public_id` TEXT NOT NULL, `learned` INTEGER NOT NULL, " +
                    "PRIMARY KEY(`public_id`))",
            )
            db.execSQL(
                "CREATE UNIQUE INDEX IF NOT EXISTS `index_catalog_items_normalized_name` ON `catalog_items` (`normalized_name`)",
            )
            db.execSQL(
                "CREATE TABLE IF NOT EXISTS `catalog_state` (`id` INTEGER NOT NULL, " +
                    "`dictionary_revision` INTEGER NOT NULL, PRIMARY KEY(`id`))",
            )
            db.execSQL("ALTER TABLE `command_subjects` ADD COLUMN `category_public_id` TEXT")
        }
    }

    /**
     * 2 -> 3 (issue #45, first cut): additive only. A command can carry the frozen wire
     * document that is resent verbatim. Every existing row gets NULL, i.e. "not frozen":
     * the queue, its order, UUIDs, intent JSON, attempts and subjects are untouched, and
     * nothing is converted or invented for commands that were already queued.
     */
    val MIGRATION_2_3: Migration = object : Migration(2, 3) {
        override fun migrate(db: SupportSQLiteDatabase) {
            db.execSQL("ALTER TABLE `commands` ADD COLUMN `wire_document` TEXT")
        }
    }

    /**
     * 3 -> 4 (issue #45, receipts and aliases): additive only. Two new, empty tables: the
     * aliases the server revealed and the receipts it gave for commands it consumed; and
     * `commands.answered_attempt`, the newest attempt the server itself answered with a
     * refusal. Every existing row gets 0, "no attempt of this command was ever answered": the
     * queue, the frozen documents and their UUIDs are exactly as they were, and a command that
     * was sent before stays unresolved until the server answers it (nothing is guessed).
     */
    val MIGRATION_3_4: Migration = object : Migration(3, 4) {
        override fun migrate(db: SupportSQLiteDatabase) {
            db.execSQL("ALTER TABLE `commands` ADD COLUMN `answered_attempt` INTEGER NOT NULL DEFAULT 0")
            db.execSQL(
                "CREATE TABLE IF NOT EXISTS `sync_aliases` (`alias_public_id` TEXT NOT NULL, " +
                    "`canonical_public_id` TEXT NOT NULL, `source_command_id` TEXT NOT NULL, " +
                    "`revision` INTEGER NOT NULL, PRIMARY KEY(`alias_public_id`))",
            )
            db.execSQL(
                "CREATE INDEX IF NOT EXISTS `index_sync_aliases_canonical_public_id` ON `sync_aliases` (`canonical_public_id`)",
            )
            db.execSQL(
                "CREATE TABLE IF NOT EXISTS `command_receipts` (`command_id` TEXT NOT NULL, `outcome` TEXT NOT NULL, " +
                    "`via_duplicate` INTEGER NOT NULL, `revision` INTEGER NOT NULL, `house_revision` INTEGER NOT NULL, " +
                    "`attempt` INTEGER NOT NULL, `data_json` TEXT NOT NULL, `received_at` INTEGER NOT NULL, " +
                    "PRIMARY KEY(`command_id`), FOREIGN KEY(`command_id`) REFERENCES `commands`(`id`) " +
                    "ON UPDATE NO ACTION ON DELETE CASCADE )",
            )
        }
    }

    /**
     * 4 -> 5 (issue #45, snapshot): additive only. A confirmed item can remember what the snapshot said
     * beyond what the screens need (the server's `normalized_name`, the instants in microseconds, the
     * position in the snapshot); the household name is kept in `sync_state`; and the archive, the trips,
     * the habituals and the tombstones get their own empty tables. Every existing row gets NULL in the
     * new columns: the queue, the aliases, the receipts, the projection and the confirmed rows are
     * exactly as they were, and `schemas/1-4.json` are untouched.
     */
    val MIGRATION_4_5: Migration = object : Migration(4, 5) {
        override fun migrate(db: SupportSQLiteDatabase) {
            db.execSQL("ALTER TABLE `sync_state` ADD COLUMN `household_name` TEXT")
            db.execSQL("ALTER TABLE `confirmed_items` ADD COLUMN `normalized_name` TEXT")
            db.execSQL("ALTER TABLE `confirmed_items` ADD COLUMN `created_at_micros` INTEGER")
            db.execSQL("ALTER TABLE `confirmed_items` ADD COLUMN `updated_at_micros` INTEGER")
            db.execSQL("ALTER TABLE `confirmed_items` ADD COLUMN `purchased_at_micros` INTEGER")
            db.execSQL("ALTER TABLE `confirmed_items` ADD COLUMN `server_order` INTEGER")
            db.execSQL(
                "CREATE TABLE IF NOT EXISTS `archived_items` (`public_id` TEXT NOT NULL, `name` TEXT NOT NULL, " +
                    "`normalized_name` TEXT NOT NULL, `category_public_id` TEXT, `status` INTEGER NOT NULL, " +
                    "`position` INTEGER, `purchased_at_micros` INTEGER, `created_at_micros` INTEGER NOT NULL, " +
                    "`updated_at_micros` INTEGER NOT NULL, `lock_version` INTEGER NOT NULL, " +
                    "`trip_public_id` TEXT NOT NULL, `server_order` INTEGER NOT NULL, PRIMARY KEY(`public_id`))",
            )
            db.execSQL("CREATE INDEX IF NOT EXISTS `index_archived_items_trip_public_id` ON `archived_items` (`trip_public_id`)")
            db.execSQL("CREATE INDEX IF NOT EXISTS `index_archived_items_normalized_name` ON `archived_items` (`normalized_name`)")
            db.execSQL(
                "CREATE TABLE IF NOT EXISTS `shopping_trips` (`public_id` TEXT NOT NULL, " +
                    "`finished_at_micros` INTEGER NOT NULL, `created_at_micros` INTEGER NOT NULL, " +
                    "`server_order` INTEGER NOT NULL, PRIMARY KEY(`public_id`))",
            )
            db.execSQL(
                "CREATE TABLE IF NOT EXISTS `habitual_items` (`public_id` TEXT NOT NULL, `name` TEXT NOT NULL, " +
                    "`normalized_name` TEXT NOT NULL, `created_at_micros` INTEGER NOT NULL, " +
                    "`server_order` INTEGER NOT NULL, PRIMARY KEY(`public_id`))",
            )
            db.execSQL(
                "CREATE TABLE IF NOT EXISTS `tombstones` (`record_type` TEXT NOT NULL, `public_id` TEXT NOT NULL, " +
                    "`revision` INTEGER NOT NULL, `server_order` INTEGER NOT NULL, " +
                    "PRIMARY KEY(`record_type`, `public_id`, `revision`))",
            )
        }
    }

    /** Contiguous chain from version 1 to [CURRENT_VERSION]. */
    val ALL: Array<Migration> = arrayOf(MIGRATION_1_2, MIGRATION_2_3, MIGRATION_3_4, MIGRATION_4_5)
}

object AlvaDatabaseFactory {
    const val FILE_NAME = "alva.db"

    /**
     * The only way the app opens the database. Durability of a committed
     * action is made explicit: a command acknowledged to the user must survive
     * the process being killed, so commits sync to disk (`synchronous = FULL`)
     * even in WAL mode.
     */
    fun builder(context: Context, name: String? = FILE_NAME): RoomDatabase.Builder<AlvaDatabase> {
        val builder = if (name == null) {
            Room.inMemoryDatabaseBuilder(context, AlvaDatabase::class.java)
        } else {
            Room.databaseBuilder(context, AlvaDatabase::class.java, name)
        }
        return builder
            .addMigrations(*AlvaMigrations.ALL)
            .addCallback(
                object : RoomDatabase.Callback() {
                    override fun onOpen(db: SupportSQLiteDatabase) {
                        db.execSQL("PRAGMA synchronous = FULL")
                    }
                },
            )
    }

    fun create(context: Context, name: String? = FILE_NAME): AlvaDatabase =
        builder(context.applicationContext, name).build()
}
